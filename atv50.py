def soma(a, b):
    print("Soma =", a + b)

def subtracao(a, b):
    print("Subtração =", a - b)

def multiplicacao(a, b):
    print("Multiplicação =", a * b)

def divisao(a, b):
    print("Divisão =", a / b)

n1 = float(input("Digite o primeiro número: "))
n2 = float(input("Digite o segundo número: "))

soma(n1, n2)
subtracao(n1, n2)
multiplicacao(n1, n2)
divisao(n1, n2)